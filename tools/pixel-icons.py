def svg(art):
    rows = art.strip('\n').split('\n')
    w = max(len(r) for r in rows)
    # one path per colour, with runs of pixels merged, so the CSS stays small
    paths = {}
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            c, start = row[x], x
            while x < len(row) and row[x] == c:
                x += 1
            if c != '.':
                paths.setdefault(c, []).append(f'M{start} {y}h{x - start}v1h-{x - start}z')
    rects = ''.join(f"<path fill='{PALETTE[c]}' d='{''.join(d)}'/>" for c, d in paths.items())
    return f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {w} {len(rows)}' shape-rendering='crispEdges'>{rects}</svg>"


